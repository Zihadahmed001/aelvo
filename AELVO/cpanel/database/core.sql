CREATE TABLE IF NOT EXISTS aelvo_users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'Active',
 email_verified_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_installation (
 id TINYINT UNSIGNED PRIMARY KEY, owner_id BIGINT UNSIGNED NULL,
 installed_at DATETIME NULL, schema_version INT NOT NULL DEFAULT 1,
 FOREIGN KEY(owner_id) REFERENCES aelvo_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT IGNORE INTO aelvo_installation(id) VALUES (1);
CREATE TABLE IF NOT EXISTS aelvo_roles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_user_roles (
 user_id BIGINT UNSIGNED NOT NULL, role_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(user_id,role_id), FOREIGN KEY(user_id) REFERENCES aelvo_users(id),
 FOREIGN KEY(role_id) REFERENCES aelvo_roles(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_role_permissions (
 role_id BIGINT UNSIGNED NOT NULL, module VARCHAR(80) NOT NULL, action VARCHAR(20) NOT NULL,
 PRIMARY KEY(role_id,module,action), FOREIGN KEY(role_id) REFERENCES aelvo_roles(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_login_attempts (
 bucket CHAR(64) PRIMARY KEY, attempts INT NOT NULL, expires_at BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT UNSIGNED NULL,
 event VARCHAR(80) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX actor_time(actor_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
