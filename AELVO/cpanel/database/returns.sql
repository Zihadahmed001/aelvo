CREATE TABLE IF NOT EXISTS aelvo_returns (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_item_id BIGINT UNSIGNED NOT NULL,
 qty INT UNSIGNED NOT NULL, restocked TINYINT NOT NULL,
 request_key CHAR(64) NOT NULL UNIQUE, request_hash CHAR(64) NOT NULL,
 reason TEXT NOT NULL, actor_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_item_id) REFERENCES aelvo_order_items(id), FOREIGN KEY(actor_id) REFERENCES aelvo_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_refunds (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 amount_minor BIGINT UNSIGNED NOT NULL, method VARCHAR(30) NOT NULL,
 reference VARCHAR(100) NOT NULL, event_id CHAR(32) NOT NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY refund_reference(method,reference),
 FOREIGN KEY(order_id) REFERENCES aelvo_orders(id), FOREIGN KEY(event_id) REFERENCES aelvo_finance_events(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
