CREATE TABLE IF NOT EXISTS aelvo_accounts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE,
 kind VARCHAR(20) NOT NULL, balance_minor BIGINT NOT NULL DEFAULT 0, active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_finance_events (
 id CHAR(32) PRIMARY KEY, request_key CHAR(64) NOT NULL UNIQUE, request_hash CHAR(64) NOT NULL,
 kind VARCHAR(30) NOT NULL, explanation TEXT NOT NULL, document_id CHAR(32) NULL,
 actor_id BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(document_id) REFERENCES aelvo_media(id), FOREIGN KEY(actor_id) REFERENCES aelvo_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_ledger (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, event_id CHAR(32) NOT NULL,
 account_id BIGINT UNSIGNED NOT NULL, delta_minor BIGINT NOT NULL,
 balance_after_minor BIGINT NOT NULL, FOREIGN KEY(event_id) REFERENCES aelvo_finance_events(id),
 FOREIGN KEY(account_id) REFERENCES aelvo_accounts(id), INDEX account_event(account_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_purchases (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reference VARCHAR(80) NOT NULL UNIQUE,
 supplier VARCHAR(180) NOT NULL, receipt_id CHAR(32) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'Draft', explanation TEXT NOT NULL,
 total_minor BIGINT UNSIGNED NOT NULL, actor_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(receipt_id) REFERENCES aelvo_media(id), FOREIGN KEY(actor_id) REFERENCES aelvo_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_purchase_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, purchase_id BIGINT UNSIGNED NOT NULL,
 variant_id BIGINT UNSIGNED NOT NULL, qty INT UNSIGNED NOT NULL, unit_cost_minor BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY(purchase_id) REFERENCES aelvo_purchases(id), FOREIGN KEY(variant_id) REFERENCES aelvo_variants(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
