CREATE TABLE IF NOT EXISTS aelvo_coupons (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(40) NOT NULL UNIQUE,
 kind VARCHAR(20) NOT NULL, amount BIGINT UNSIGNED NOT NULL,
 minimum_minor BIGINT UNSIGNED NOT NULL DEFAULT 0, cap_minor BIGINT UNSIGNED NULL,
 usage_limit INT UNSIGNED NULL, used_count INT UNSIGNED NOT NULL DEFAULT 0,
 starts_at BIGINT UNSIGNED NULL, ends_at BIGINT UNSIGNED NULL,
 active TINYINT NOT NULL DEFAULT 0, version INT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_coupon_redemptions (
 order_id BIGINT UNSIGNED PRIMARY KEY, coupon_id BIGINT UNSIGNED NOT NULL,
 code VARCHAR(40) NOT NULL, discount_minor BIGINT UNSIGNED NOT NULL,
 released_at BIGINT UNSIGNED NULL,
 FOREIGN KEY(order_id) REFERENCES aelvo_orders(id), FOREIGN KEY(coupon_id) REFERENCES aelvo_coupons(id),
 INDEX coupon_usage(coupon_id,released_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
