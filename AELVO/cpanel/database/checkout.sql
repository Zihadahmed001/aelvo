CREATE TABLE IF NOT EXISTS aelvo_checkouts (
 id CHAR(64) PRIMARY KEY, session_hash CHAR(64) NOT NULL,
 payload MEDIUMTEXT NOT NULL, total_minor BIGINT UNSIGNED NOT NULL,
 expires_at BIGINT UNSIGNED NOT NULL, otp_hash VARCHAR(255) NULL,
 otp_expires_at BIGINT UNSIGNED NOT NULL DEFAULT 0,
 otp_sent_at BIGINT UNSIGNED NOT NULL DEFAULT 0, otp_attempts INT UNSIGNED NOT NULL DEFAULT 0,
 verified_at BIGINT UNSIGNED NULL, order_id BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES aelvo_orders(id), INDEX expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
