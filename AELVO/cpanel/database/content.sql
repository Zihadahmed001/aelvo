CREATE TABLE IF NOT EXISTS aelvo_content (
 content_key VARCHAR(80) PRIMARY KEY, draft MEDIUMTEXT NOT NULL,
 published MEDIUMTEXT NULL, version INT UNSIGNED NOT NULL DEFAULT 1,
 published_version INT UNSIGNED NULL, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_content_media (
 media_id CHAR(32) PRIMARY KEY, FOREIGN KEY(media_id) REFERENCES aelvo_media(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
