CREATE TABLE IF NOT EXISTS aelvo_products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(180) NOT NULL,
 name_bn VARCHAR(180) NOT NULL DEFAULT '', slug VARCHAR(180) NOT NULL UNIQUE,
 category VARCHAR(80) NOT NULL, description TEXT NOT NULL, description_bn TEXT NOT NULL,
 details TEXT NOT NULL, price_minor BIGINT UNSIGNED NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'Draft', version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX catalogue(status,category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_variants (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL,
 sku VARCHAR(80) NOT NULL UNIQUE, colour VARCHAR(80) NOT NULL, colour_hex CHAR(7) NOT NULL,
 size VARCHAR(30) NOT NULL, stock INT UNSIGNED NOT NULL DEFAULT 0,
 reserved INT UNSIGNED NOT NULL DEFAULT 0, active TINYINT NOT NULL DEFAULT 1,
 UNIQUE KEY product_colour_size(product_id,colour,size),
 FOREIGN KEY(product_id) REFERENCES aelvo_products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_media (
 id CHAR(32) PRIMARY KEY, disk_name VARCHAR(100) NOT NULL UNIQUE,
 original_name VARCHAR(180) NOT NULL, mime VARCHAR(80) NOT NULL, bytes BIGINT UNSIGNED NOT NULL,
 is_public TINYINT NOT NULL DEFAULT 0, owner_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(owner_id) REFERENCES aelvo_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_product_media (
 product_id BIGINT UNSIGNED NOT NULL, media_id CHAR(32) NOT NULL,
 colour VARCHAR(80) NOT NULL DEFAULT '', position INT NOT NULL DEFAULT 0,
 PRIMARY KEY(product_id,media_id), FOREIGN KEY(product_id) REFERENCES aelvo_products(id),
 FOREIGN KEY(media_id) REFERENCES aelvo_media(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, variant_id BIGINT UNSIGNED NOT NULL,
 stock_delta INT NOT NULL, reserved_delta INT NOT NULL,
 source_type VARCHAR(40) NOT NULL, source_id VARCHAR(80) NOT NULL,
 explanation TEXT NOT NULL, actor_id BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(variant_id) REFERENCES aelvo_variants(id), INDEX variant_time(variant_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reference VARCHAR(40) NOT NULL UNIQUE,
 request_key CHAR(64) NOT NULL UNIQUE, request_hash CHAR(64) NOT NULL,
 customer_name VARCHAR(120) NOT NULL, phone VARCHAR(20) NOT NULL,
 address TEXT NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'Pending',
 payment_status VARCHAR(30) NOT NULL DEFAULT 'Unpaid', payment_method VARCHAR(30) NOT NULL,
 subtotal_minor BIGINT UNSIGNED NOT NULL, delivery_minor BIGINT UNSIGNED NOT NULL,
 total_minor BIGINT UNSIGNED NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX status_time(status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 variant_id BIGINT UNSIGNED NOT NULL, product_name VARCHAR(180) NOT NULL,
 variant_label VARCHAR(160) NOT NULL, qty INT UNSIGNED NOT NULL,
 unit_price_minor BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY(order_id) REFERENCES aelvo_orders(id), FOREIGN KEY(variant_id) REFERENCES aelvo_variants(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_settings (
 setting_key VARCHAR(80) PRIMARY KEY, payload MEDIUMTEXT NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_provider_secrets (
 provider VARCHAR(40) PRIMARY KEY, ciphertext MEDIUMTEXT NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_staff_profiles (
 user_id BIGINT UNSIGNED PRIMARY KEY, phone VARCHAR(20) NOT NULL DEFAULT '',
 notes TEXT NOT NULL, FOREIGN KEY(user_id) REFERENCES aelvo_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
