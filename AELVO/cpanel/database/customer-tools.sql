CREATE TABLE IF NOT EXISTS aelvo_customer_security (
 customer_id BIGINT UNSIGNED PRIMARY KEY,
 session_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
 changed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES aelvo_customers(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS aelvo_customer_addresses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 customer_id BIGINT UNSIGNED NOT NULL,
 label VARCHAR(80) NOT NULL, recipient VARCHAR(120) NOT NULL,
 phone VARCHAR(20) NOT NULL, address TEXT NOT NULL,
 zone VARCHAR(20) NOT NULL, version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES aelvo_customers(id),
 INDEX customer_address(customer_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
